-- Monolith direct payment confirmation (backend-app). Apply only in the approved cutover;
-- the API never runs this file at startup.
--
-- Provider payments that may need manual cancellation or reconciliation. Rows hold short
-- codes only: no provider response text, card data or secrets.
CREATE TABLE pawbridge_payment.payment_compensation_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_key VARCHAR(100),
    order_id VARCHAR(100),
    user_id BIGINT,
    amount BIGINT,
    stage VARCHAR(30) NOT NULL CHECK (stage IN ('CANCEL_FAILED','UNKNOWN_RESULT')),
    reason VARCHAR(50) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    resolved_at TIMESTAMP(6)
);
CREATE INDEX idx_payment_compensation_records_open
    ON pawbridge_payment.payment_compensation_records (created_at) WHERE resolved_at IS NULL;

-- At most one DONE payment per order. Check existing rows for duplicate DONE order_id values
-- before applying; creation fails instead of silently choosing one.
CREATE UNIQUE INDEX ux_payments_order_id_done
    ON pawbridge_payment.payments (order_id) WHERE status = 'DONE';
