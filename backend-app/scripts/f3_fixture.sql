    AND title COLLATE "C" !~ U&'[\+010000-\+10FFFF]');
-- outbox_events is kept only as the legacy oracle's table (the legacy service writes POST_* rows there).
-- The candidate monolith no longer writes it, so the writer role gets no privilege on it.
CREATE TABLE pawbridge_community.outbox_events (
 outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 aggregate_id VARCHAR(255) NOT NULL, aggregate_type VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, event_id VARCHAR(255) NOT NULL UNIQUE,
 payload JSON NOT NULL, type VARCHAR(255) NOT NULL,
 CONSTRAINT ck_rollback_charset_outbox_events CHECK (
 aggregate_id COLLATE "C" !~ U&'[\+010000-\+10FFFF]'
 AND aggregate_type COLLATE "C" !~ U&'[\+010000-\+10FFFF]'
 AND event_id COLLATE "C" !~ U&'[\+010000-\+10FFFF]'
 AND type COLLATE "C" !~ U&'[\+010000-\+10FFFF]')
);
CREATE TABLE pawbridge_community.post_search_documents (
 post_id BIGINT PRIMARY KEY REFERENCES pawbridge_community.posts(post_id) ON DELETE CASCADE,
 title_hash TEXT NOT NULL, content_hash TEXT NOT NULL,
 analyzer_version VARCHAR(64) NOT NULL, tokens TSVECTOR NOT NULL
);
CREATE INDEX idx_post_search_tokens ON pawbridge_community.post_search_documents USING GIN(tokens);
