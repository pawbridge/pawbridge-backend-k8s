def token(identity, expiry, role='ROLE_USER'):
    claims = {'userId': identity, 'role': role, 'exp': expiry}
    encoded = base64.urlsafe_b64encode(json.dumps(claims).encode()).decode().rstrip('=')
    return 'synthetic.' + encoded + '.signature'


