package com.pawbridge.backend.user.internal.favorite.web;

import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

@RestControllerAdvice(assignableTypes = FavoriteStatusController.class)
public final class FavoriteStatusExceptionHandler {
    private static final Logger LOG = LoggerFactory.getLogger(FavoriteStatusExceptionHandler.class);
    private static final int MAX_LOGGED_CAUSES = 4;
    private static final int MAX_LOGGED_FRAMES = 6;
    private static final int MAX_DIAGNOSTIC_LENGTH = 4096;

    @ExceptionHandler(RuntimeException.class)
    public ResponseEntity<FavoriteStatusController.Response<Void>> serverError(RuntimeException failure) {
        // The original advice's Hibernate-only handler does not catch Spring path conversion failures.
        LOG.error("Unexpected favorite status lookup failure (exception messages omitted): {}", diagnosticTrace(failure));
        return ResponseEntity.internalServerError()
                .body(new FavoriteStatusController.Response<>(500, "서버 에러!", null));
    }

    private static String diagnosticTrace(Throwable failure) {
        var trace = new StringBuilder();
        Set<Throwable> visited = Collections.newSetFromMap(new IdentityHashMap<>());
        Throwable current = failure;
        for (int depth = 0; current != null && depth < MAX_LOGGED_CAUSES && visited.add(current); depth++) {
            trace.append(current.getClass().getName()).append('\n');
            StackTraceElement[] frames = current.getStackTrace();
            for (int index = 0; index < Math.min(frames.length, MAX_LOGGED_FRAMES); index++) {
                StackTraceElement frame = frames[index];
                trace.append("  at ").append(frame.getClassName()).append('.').append(frame.getMethodName())
                        .append(":").append(frame.getLineNumber()).append('\n');
            }
            current = current.getCause();
        }
        return trace.substring(0, Math.min(trace.length(), MAX_DIAGNOSTIC_LENGTH));
    }
}
