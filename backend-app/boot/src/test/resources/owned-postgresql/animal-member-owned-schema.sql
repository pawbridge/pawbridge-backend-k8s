CREATE TABLE pawbridge_animal.shelters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_reg_no varchar(50) NOT NULL UNIQUE,
    name varchar(200) NOT NULL,
    phone varchar(50),
    address varchar(500),
    owner_name varchar(100),
    organization_name varchar(200),
    email varchar(100),
    introduction varchar(2000),
    adoption_procedure varchar(2000),
    operating_hours varchar(200),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone
);
CREATE TABLE pawbridge_animal.animals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apms_desertion_no varchar(50) UNIQUE,
    apms_notice_no varchar(100) NOT NULL,
    species varchar(20) NOT NULL,
    breed varchar(100),
    birth_year integer,
    weight varchar(50),
    color varchar(100),
    gender varchar(20) NOT NULL,
    neuter_status varchar(20) NOT NULL,
    special_mark varchar(1000),
    apms_process_state varchar(50),
    notice_start_date date NOT NULL,
    notice_end_date date NOT NULL,
    apms_updated_at timestamp(6) without time zone,
    happen_date date,
    happen_place varchar(200),
    image_url varchar(500),
    image_url2 varchar(500),
    shelter_id bigint NOT NULL REFERENCES pawbridge_animal.shelters(id),
    status varchar(30) NOT NULL,
    api_source varchar(20) NOT NULL,
    favorite_count integer NOT NULL,
    description varchar(2000),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone
);
