-- Isolated test fixture only. Root replaces the three placeholders before applying it.
-- No password is present here. The Java tests never execute DDL or GRANT.
-- Column types/PK/unique constraints follow the two PostgreSQL V1 resources.
-- This six-table model deliberately omits User users/FK and Animal shelter/other columns.
-- It is not a complete migration or an original JPA oracle.
BEGIN;
DO $$ BEGIN
    IF current_database() <> '__OWNED_DATABASE__'
       OR current_database() !~ '^pb_favorite_owned_[0-9a-f]{8,32}$'
    THEN RAISE EXCEPTION 'Owned favorite fixture database mismatch'; END IF;
END $$;
CREATE TABLE public.pawbridge_owned_fixture (
    value varchar(50) PRIMARY KEY CHECK (value = 'favorite-delivery-v1'),
    owner_marker varchar(32) NOT NULL CHECK (owner_marker ~ '^[0-9a-f]{32}$')
);
INSERT INTO public.pawbridge_owned_fixture VALUES ('favorite-delivery-v1', '__OWNED_OWNER_MARKER__');
CREATE SCHEMA pawbridge_user;
CREATE SCHEMA pawbridge_animal;
REVOKE ALL ON SCHEMA pawbridge_user, pawbridge_animal FROM PUBLIC;
CREATE TABLE pawbridge_user.favorites (
    favorite_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id bigint NOT NULL, created_at timestamp(6) NOT NULL, user_id bigint NOT NULL,
    CONSTRAINT uk_user_animal UNIQUE(user_id, animal_id)
);
CREATE INDEX idx_favorite_animal_id ON pawbridge_user.favorites(animal_id);
CREATE TABLE pawbridge_user.outbox_events (
    outbox_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id varchar(100) NOT NULL, aggregate_type varchar(50) NOT NULL,
    created_at timestamp(6) NOT NULL, event_id varchar(36) NOT NULL UNIQUE,
    event_type varchar(50) NOT NULL, payload json NOT NULL, topic varchar(100) NOT NULL
);
CREATE INDEX idx_outbox_created_at ON pawbridge_user.outbox_events(created_at);
CREATE TABLE pawbridge_user.processed_events (
    event_id varchar(36) PRIMARY KEY, event_type varchar(50) NOT NULL, processed_at timestamp(6) NOT NULL
);
CREATE INDEX idx_processed_at ON pawbridge_user.processed_events(processed_at);
CREATE TABLE pawbridge_animal.animals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    favorite_count int NOT NULL, updated_at timestamp(6) without time zone DEFAULT NULL
);
CREATE TABLE pawbridge_animal.outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id varchar(50) NOT NULL, aggregate_type varchar(50) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL, event_id varchar(50) NOT NULL,
    event_type varchar(50) NOT NULL, payload text NOT NULL, topic varchar(100) NOT NULL,
    CONSTRAINT uk_animal_outbox_event UNIQUE(event_id)
);
CREATE INDEX idx_outbox_created_at ON pawbridge_animal.outbox_events(created_at);
CREATE TABLE pawbridge_animal.processed_events (
    event_id varchar(50) PRIMARY KEY, event_type varchar(50) NOT NULL,
    processed_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_processed_at ON pawbridge_animal.processed_events(processed_at);
REVOKE ALL ON ALL TABLES IN SCHEMA pawbridge_user, pawbridge_animal FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA pawbridge_user, pawbridge_animal FROM PUBLIC;
GRANT CONNECT ON DATABASE "__OWNED_DATABASE__" TO "__OWNED_WRITER__";
GRANT USAGE ON SCHEMA pawbridge_user, pawbridge_animal TO "__OWNED_WRITER__";
GRANT SELECT ON public.pawbridge_owned_fixture TO "__OWNED_WRITER__";
GRANT SELECT ON pawbridge_user.outbox_events TO "__OWNED_WRITER__";
GRANT SELECT, INSERT ON pawbridge_user.processed_events TO "__OWNED_WRITER__";
GRANT SELECT(user_id, animal_id), DELETE ON pawbridge_user.favorites TO "__OWNED_WRITER__";
GRANT SELECT(id, favorite_count, updated_at), UPDATE(favorite_count, updated_at)
    ON pawbridge_animal.animals TO "__OWNED_WRITER__";
GRANT SELECT, INSERT ON pawbridge_animal.outbox_events TO "__OWNED_WRITER__";
GRANT USAGE ON SEQUENCE pawbridge_animal.outbox_events_id_seq TO "__OWNED_WRITER__";
GRANT SELECT, INSERT ON pawbridge_animal.processed_events TO "__OWNED_WRITER__";
COMMIT;
