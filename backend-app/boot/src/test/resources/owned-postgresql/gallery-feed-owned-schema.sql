-- No archive worker, gallery publication, vector, search projection or production DDL is added.
BEGIN;
SELECT set_config('pawbridge.owned_database', :'owned_database', true),
       set_config('pawbridge.owned_marker', :'owned_marker', true),
       set_config('pawbridge.owned_reader', :'owned_reader', true);
DO $$ BEGIN
 IF current_database() <> current_setting('pawbridge.owned_database')
    OR current_database() !~ '^pb_gallery_feed_owned_[0-9a-f]{12}$'
    OR current_setting('server_version_num') <> '170011'
 THEN RAISE EXCEPTION 'Owned Gallery database mismatch'; END IF;
 IF current_setting('pawbridge.owned_reader') <> 'pb_gallery_feed_reader'
    OR current_user = current_setting('pawbridge.owned_reader')
    OR (SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname=current_database()) <> current_user
 THEN RAISE EXCEPTION 'Owned Gallery fixture owner mismatch'; END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname=current_setting('pawbridge.owned_reader')
                AND rolcanlogin AND NOT rolsuper AND NOT rolcreatedb AND NOT rolcreaterole
                AND NOT rolreplication AND NOT rolbypassrls AND NOT rolinherit)
    OR EXISTS (SELECT 1 FROM pg_auth_members m JOIN pg_roles r ON r.oid=m.member
               WHERE r.rolname=current_setting('pawbridge.owned_reader'))
 THEN RAISE EXCEPTION 'Owned Gallery reader role mismatch'; END IF;
 IF current_setting('pawbridge.owned_marker') !~ '^[0-9a-f]{32}$'
    OR (SELECT count(*) FROM public.pb_gallery_feed_fixture) <> 1
    OR NOT EXISTS (SELECT 1 FROM public.pb_gallery_feed_fixture WHERE marker=current_setting('pawbridge.owned_marker'))
 THEN RAISE EXCEPTION 'Owned Gallery marker mismatch'; END IF;
END $$;
CREATE SCHEMA pawbridge_animal;
REVOKE ALL ON SCHEMA pawbridge_animal FROM PUBLIC;
SET LOCAL search_path=pawbridge_animal,public;
CREATE TABLE shelters (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone DEFAULT NULL,
  address varchar(500) DEFAULT NULL,
  adoption_procedure varchar(2000) DEFAULT NULL,
  care_reg_no varchar(50) NOT NULL,
  email varchar(100) DEFAULT NULL,
  introduction varchar(2000) DEFAULT NULL,
  name varchar(200) NOT NULL,
  operating_hours varchar(200) DEFAULT NULL,
  organization_name varchar(200) DEFAULT NULL,
  owner_name varchar(100) DEFAULT NULL,
  phone varchar(50) DEFAULT NULL,
  PRIMARY KEY (id),
  CONSTRAINT idx_care_reg_no UNIQUE (care_reg_no)
);
CREATE TABLE animals (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone DEFAULT NULL,
  api_source varchar(32) CHECK (api_source IN ('APMS_ANIMAL','GYEONGGI','MANUAL','UNKNOWN')) NOT NULL,
  apms_desertion_no varchar(50) DEFAULT NULL,
  apms_notice_no varchar(100) NOT NULL,
  apms_process_state varchar(50) DEFAULT NULL,
  apms_updated_at timestamp(6) without time zone DEFAULT NULL,
  birth_year int DEFAULT NULL,
  breed varchar(100) DEFAULT NULL,
  color varchar(100) DEFAULT NULL,
  description varchar(2000) DEFAULT NULL,
  favorite_count int NOT NULL,
  gender varchar(32) CHECK (gender IN ('FEMALE','MALE','UNKNOWN')) NOT NULL,
  happen_date date DEFAULT NULL,
  happen_place varchar(200) DEFAULT NULL,
  image_url varchar(500) DEFAULT NULL,
  image_url2 varchar(500) DEFAULT NULL,
  neuter_status varchar(32) CHECK (neuter_status IN ('NO','UNKNOWN','YES')) NOT NULL,
  notice_end_date date NOT NULL,
  notice_start_date date NOT NULL,
  special_mark varchar(1000) DEFAULT NULL,
  species varchar(32) CHECK (species IN ('CAT','DOG','ETC')) NOT NULL,
  status varchar(32) CHECK (status IN ('ADOPTED','ADOPTION_PENDING','DONATED','ESCAPED','EUTHANIZED','NATURAL_DEATH','NOTICE','PROTECT','RELEASED','RETURNED','UNKNOWN')) NOT NULL,
  weight varchar(50) DEFAULT NULL,
  shelter_id bigint NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT idx_apms_desertion_no UNIQUE (apms_desertion_no),
  CONSTRAINT FK7fmlpw3o4ourhtv3qy8gl6cn5 FOREIGN KEY (shelter_id) REFERENCES shelters (id)
);
CREATE INDEX idx_species_status ON animals (species,status);
CREATE INDEX idx_notice_end_date ON animals (notice_end_date);
CREATE INDEX idx_shelter_id ON animals (shelter_id);
CREATE INDEX idx_apms_notice_no ON animals (apms_notice_no);
CREATE TABLE apms_photo_archive (
  animal_id BIGINT NOT NULL,
  slot SMALLINT NOT NULL,
  desertion_no VARCHAR(50) NOT NULL,
  source_url VARCHAR(500) NULL,
  generation BIGINT NOT NULL DEFAULT 1,
  state VARCHAR(16) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  lease_token VARCHAR(36) NULL,
  lease_until timestamp(6) without time zone NULL,
  error_code VARCHAR(64) NULL,
  archived_source_url VARCHAR(500) NULL,
  source_sha256 CHAR(64) NULL,
  stored_sha256 CHAR(64) NULL,
  object_key VARCHAR(200) NULL,
  content_type VARCHAR(32) NULL,
  stored_bytes INT NULL,
  width INT NULL,
  height INT NULL,
  recipe VARCHAR(64) NULL,
  archived_at timestamp(6) without time zone NULL,
  PRIMARY KEY (animal_id, slot),
  CONSTRAINT fk_photo_animal FOREIGN KEY (animal_id) REFERENCES animals(id) ON DELETE CASCADE,
  CONSTRAINT chk_photo_slot CHECK (slot IN (1,2))
);
CREATE INDEX idx_photo_due ON apms_photo_archive (state, next_attempt_at);
CREATE INDEX idx_photo_lease ON apms_photo_archive (state, lease_until);

