-- Browser refresh sessions. Only the SHA-256 hex digest of each opaque refresh token is stored.
-- refresh_tokens stays until every running build has stopped writing it; a later migration removes it.
CREATE TABLE auth_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    previous_token_hash VARCHAR(64) CHECK (previous_token_hash ~ '^[0-9a-f]{64}$'),
    rotated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ NOT NULL,
    -- Idle expiry, moved forward on every rotation but never past absolute_expires_at.
    expires_at TIMESTAMPTZ NOT NULL,
    absolute_expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX idx_auth_sessions_user_id ON auth_sessions (user_id);
-- A rejected refresh looks up the presented hash here to tell a concurrent retry from token reuse.
CREATE INDEX idx_auth_sessions_previous_token_hash ON auth_sessions (previous_token_hash)
    WHERE previous_token_hash IS NOT NULL;

-- The schema default privileges already cover this in production; the explicit grant keeps the
-- application role's access visible here. Disposable databases without that role skip it.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pawbridge_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON auth_sessions TO pawbridge_app;
    END IF;
END
$$;
