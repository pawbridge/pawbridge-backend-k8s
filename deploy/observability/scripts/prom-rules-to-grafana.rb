# Converts the Prometheus rule files into Grafana-managed alert rules (file provisioning).
#
# Why: Grafana's built-in Alertmanager does not accept alerts pushed by Prometheus, so the rules are
# evaluated by Grafana itself against the Prometheus datasource. Prometheus keeps the same rule files
# only for its own UI (/alerts); it no longer sends notifications.
#
# Each PromQL rule `expr` is a filter that returns series only while the condition holds (including the
# NaN check `x != x`). `group without () (expr)` turns every returned series into the value 1 while
# keeping its labels, so the Grafana condition is simply "value > 0" and "no series" means OK.
#
# Usage: ruby scripts/prom-rules-to-grafana.rb prometheus/rules/urgent.yml prometheus/rules/warning.yml \
#          > grafana/provisioning/alerting/rules.yaml
require "yaml"

def seconds(duration)
  return 0 if duration.nil? || duration.to_s.empty?
  units = { "s" => 1, "m" => 60, "h" => 3600 }
  duration.to_s.scan(/(\d+)([smh])/).sum { |amount, unit| amount.to_i * units.fetch(unit) }
end

# Prometheus templates use `$value` (a float). In Grafana `$value` is a string description, so value-based
# functions such as humanizePercentage fail. Point them at query B, which returns the raw rule value.
def grafana_annotations(prom_annotations)
  (prom_annotations || {}).transform_values { |text| text.gsub("$value", "$values.B.Value") }
end

def grafana_rule(prom_rule, group_name)
  for_seconds = seconds(prom_rule["for"])
  raw_expression = prom_rule["expr"].strip
  {
    "uid" => "pb-#{prom_rule['alert'].gsub(/[^A-Za-z0-9]/, '').downcase}"[0, 40],
    "title" => prom_rule["alert"],
    "condition" => "C",
    "data" => [
      {
        "refId" => "A",
        "relativeTimeRange" => { "from" => 600, "to" => 0 },
        "datasourceUid" => "prometheus",
        "model" => {
          "refId" => "A",
          "expr" => "group without () (#{raw_expression})",
          "instant" => true,
          "intervalMs" => 1000,
          "maxDataPoints" => 43200,
        },
      },
      {
        "refId" => "B",
        "relativeTimeRange" => { "from" => 600, "to" => 0 },
        "datasourceUid" => "prometheus",
        "model" => {
          "refId" => "B",
          "expr" => raw_expression,
          "instant" => true,
          "intervalMs" => 1000,
          "maxDataPoints" => 43200,
        },
      },
      {
        "refId" => "C",
        "datasourceUid" => "__expr__",
        "model" => {
          "refId" => "C",
          "type" => "threshold",
          "expression" => "A",
          "conditions" => [{ "evaluator" => { "type" => "gt", "params" => [0] } }],
        },
      },
    ],
    "noDataState" => "OK",
    "execErrState" => "Error",
    "for" => "#{for_seconds}s",
    "labels" => (prom_rule["labels"] || {}).merge("source_group" => group_name),
    "annotations" => grafana_annotations(prom_rule["annotations"]),
    "isPaused" => false,
  }
end

groups = ARGV.flat_map { |path| YAML.load_file(path)["groups"] }
output = {
  "apiVersion" => 1,
  "groups" => groups.map do |group|
    {
      "orgId" => 1,
      "name" => group["name"],
      "folder" => "PawBridge",
      "interval" => "1m",
      "rules" => group["rules"].select { |rule| rule["alert"] }.map { |rule| grafana_rule(rule, group["name"]) },
    }
  end,
}
puts "# Generated by scripts/prom-rules-to-grafana.rb from #{ARGV.join(', ')} — edit the Prometheus rule files, then regenerate."
puts output.to_yaml
