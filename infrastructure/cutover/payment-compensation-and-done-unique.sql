-- Monolith direct payment confirmation (backend-app) cutover DDL.
-- Apply MANUALLY, once, at the approved cutover with a schema owner account. Nothing runs this file
-- automatically: it is deliberately outside every Flyway location and every CI fixture.
--
-- 1) Provider payments that may need manual cancellation or reconciliation. Rows hold short
--    codes only: no provider response text, card data or secrets. Toss payment keys are up to 200 chars.
CREATE TABLE pawbridge_payment.payment_compensation_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_key VARCHAR(200),
    order_id VARCHAR(200),
    user_id BIGINT,
    amount BIGINT,
    stage VARCHAR(30) NOT NULL CHECK (stage IN ('CANCEL_FAILED','UNKNOWN_RESULT')),
    reason VARCHAR(50) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    resolved_at TIMESTAMP(6)
);
CREATE INDEX idx_payment_compensation_records_open
    ON pawbridge_payment.payment_compensation_records (created_at) WHERE resolved_at IS NULL;

-- 2) At most one DONE payment per order. Check existing rows for duplicate DONE order_id values
--    first; creation fails instead of silently choosing one.
CREATE UNIQUE INDEX ux_payments_order_id_done
    ON pawbridge_payment.payments (order_id) WHERE status = 'DONE';

